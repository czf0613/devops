import { afterEach, expect, it, vi } from 'vitest'
import { enableAutoUnmount, flushPromises, mount } from '@vue/test-utils'
import RepositoryCloneMenu from '../src/components/RepositoryCloneMenu.vue'

enableAutoUnmount(afterEach)
afterEach(() => { vi.useRealTimers(); vi.unstubAllGlobals(); document.body.innerHTML = '' })
const cloneUrl = `https://devops.example.com/git/owner/${'long-repository-'.repeat(8)}.git`

it('closes with Escape, the close button, outside clicks and focus leaving the panel', async () => {
  const wrapper = mount(RepositoryCloneMenu, { props: { cloneUrl }, attachTo: document.body })
  const trigger = wrapper.get('button.clone-trigger')
  await trigger.trigger('click')
  expect(trigger.attributes('aria-expanded')).toBe('true')
  const code = wrapper.get('[aria-label="HTTPS 克隆地址"]')
  expect(code.text()).toBe(cloneUrl)
  ;(code.element as HTMLElement).focus()
  await code.trigger('keydown', { key: 'Escape' })
  expect(wrapper.find('section').exists()).toBe(false)
  expect(document.activeElement).toBe(trigger.element)
  await trigger.trigger('click')
  document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }))
  await flushPromises()
  expect(wrapper.find('section').exists()).toBe(false)
  await trigger.trigger('click')
  await wrapper.get('[aria-label="关闭克隆面板"]').trigger('click')
  expect(trigger.attributes('aria-expanded')).toBe('false')
  await trigger.trigger('click')
  document.body.dispatchEvent(new Event('pointerdown', { bubbles: true }))
  await flushPromises()
  expect(wrapper.find('section').exists()).toBe(false)
  const outside = document.createElement('button')
  document.body.append(outside)
  await trigger.trigger('click')
  outside.focus()
  await flushPromises()
  expect(wrapper.find('section').exists()).toBe(false)
})

it('copies the complete URL, expires feedback, and clears state when the repository changes', async () => {
  vi.useFakeTimers()
  const writeText = vi.fn().mockResolvedValue(undefined)
  vi.stubGlobal('navigator', { clipboard: { writeText } })
  const wrapper = mount(RepositoryCloneMenu, { props: { cloneUrl } })
  await wrapper.get('.clone-trigger').trigger('click')
  await wrapper.get('[aria-label="复制克隆地址"]').trigger('click')
  await flushPromises()
  expect(writeText).toHaveBeenCalledWith(cloneUrl)
  expect(wrapper.get('[role="status"]').text()).toBe('克隆地址已复制')
  await vi.advanceTimersByTimeAsync(2000)
  expect(wrapper.get('[role="status"]').text()).toBe('')
  await wrapper.get('[aria-label="复制克隆地址"]').trigger('click')
  await flushPromises()
  await wrapper.setProps({ cloneUrl: 'https://devops.example.com/git/new/project.git' })
  expect(wrapper.find('section').exists()).toBe(false)
  expect(vi.getTimerCount()).toBe(0)
})

it('keeps the address selectable when clipboard access fails', async () => {
  vi.stubGlobal('navigator', { clipboard: { writeText: vi.fn().mockRejectedValue(new Error('denied')) } })
  const wrapper = mount(RepositoryCloneMenu, { props: { cloneUrl } })
  await wrapper.get('.clone-trigger').trigger('click')
  await wrapper.get('[aria-label="复制克隆地址"]').trigger('click')
  await flushPromises()
  expect(wrapper.get('[role="alert"]').text()).toContain('请选中地址手动复制')
  expect(wrapper.get('[aria-label="HTTPS 克隆地址"]').text()).toBe(cloneUrl)
})
